import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

const companyId = "123e4567-e89b-42d3-a456-426614174000";
const otherCompanyId = "123e4567-e89b-42d3-a456-426614174001";
const categoryId = 1;
const productId = "223e4567-e89b-42d3-a456-426614174000";
const customerId = "323e4567-e89b-42d3-a456-426614174000";
const deliveredOrderId = "423e4567-e89b-42d3-a456-426614174000";
const deliveredDetailId = "523e4567-e89b-42d3-a456-426614174000";
const requestKey = "623e4567-e89b-42d3-a456-426614174000";
const firstAdminId = "723e4567-e89b-42d3-a456-426614174000";
const secondAdminId = "823e4567-e89b-42d3-a456-426614174000";
let database: PGlite;

async function runMigrations() {
  const catalogMigration = await readFile(new URL("../../supabase/migrations/20261103000000_add_product_catalog_metadata.sql", import.meta.url), "utf8");
  const operationsMigration = await readFile(new URL("../../supabase/migrations/20261109000000_scope_operations_and_checkout.sql", import.meta.url), "utf8");
  await database.exec(catalogMigration);
  await database.exec(operationsMigration);
}

async function bootstrapLegacySchema() {
  await database.exec(`
    create role service_role;
    create role anon;
    create role authenticated;
    create table public.companies (id uuid primary key, name text not null);
    create table public.roles (id integer generated by default as identity primary key, name text not null unique);
    create table public.users (id uuid primary key, company_id uuid not null references public.companies(id), full_name text not null, email text not null, is_active boolean not null default true);
    create table public.user_roles (user_id uuid not null references public.users(id), role_id integer not null references public.roles(id), primary key (user_id, role_id));
    create table public.categories (id integer generated by default as identity primary key, name text not null);
    create table public.products (
      id uuid primary key,
      company_id uuid not null references public.companies(id),
      category_id integer references public.categories(id),
      name text not null,
      description text,
      price numeric(10,2) not null,
      file_url text,
      is_active boolean not null default true,
      created_at timestamptz not null default now(),
      is_featured boolean not null default false,
      is_new boolean not null default false,
      product_type text not null default 'download'
    );
    create table public.customers (
      id uuid primary key default gen_random_uuid(),
      company_id uuid not null references public.companies(id),
      full_name text not null,
      email text not null
    );
    create table public.orders (
      id uuid primary key default gen_random_uuid(),
      customer_id uuid not null references public.customers(id),
      status text not null,
      total numeric(12,2) not null,
      created_at timestamptz not null default now()
    );
    create table public.order_details (
      id uuid primary key default gen_random_uuid(),
      order_id uuid not null references public.orders(id),
      product_id uuid not null references public.products(id),
      quantity integer not null,
      unit_price numeric(10,2) not null,
      license_key text,
      download_expires_at timestamptz
    );

    insert into public.companies (id, name) values
      ('${companyId}', 'Empresa Uno'),
      ('${otherCompanyId}', 'Empresa Dos');
    insert into public.roles (name) values ('admin'), ('seller'), ('support');
    insert into public.categories (id, name) values (${categoryId}, 'Plantillas');
    insert into public.products (id, company_id, category_id, name, price, file_url)
      values ('${productId}', '${companyId}', ${categoryId}, 'Plantilla inicial', 12.50, '${companyId}/plantilla.pdf');
    insert into public.customers (id, company_id, full_name, email)
      values ('${customerId}', '${companyId}', 'Cliente Inicial', 'cliente@example.com');
    insert into public.orders (id, customer_id, status, total, created_at)
      values ('${deliveredOrderId}', '${customerId}', 'delivered', 12.50, '2026-01-01T00:00:00Z');
    insert into public.order_details (id, order_id, product_id, quantity, unit_price, download_expires_at)
      values ('${deliveredDetailId}', '${deliveredOrderId}', '${productId}', 1, 12.50, '2026-03-03T00:00:00Z');
  `);
}

describe("database order workflows", () => {
  beforeEach(async () => {
    database = new PGlite();
    await bootstrapLegacySchema();
    await runMigrations();
  });

  afterEach(async () => {
    await database.close();
  });

  it("backfills tenant ownership and delivery time from legacy data", async () => {
    const result = await database.query<{ company_id: string; delivered_at: Date }>(
      "select order_row.company_id, order_row.delivered_at from public.orders as order_row where order_row.id = $1",
      [deliveredOrderId],
    );
    expect(result.rows[0].company_id).toBe(companyId);
    expect(new Date(result.rows[0].delivered_at).toISOString()).toBe("2026-02-01T00:00:00.000Z");

    const categories = await database.query<{ company_id: string }>("select company_id from public.categories where id = $1", [categoryId]);
    expect(categories.rows[0].company_id).toBe(companyId);
  });

  it("creates checkout atomically and returns the same order on retry", async () => {
    const args = [companyId, "Nuevo Cliente", "nuevo@example.com", JSON.stringify([{ productId, quantity: 2 }]), requestKey, "a".repeat(64)];
    const first = await database.query<{ order_id: string; total: string; created: boolean; order_created_at: Date }>(
      "select * from public.create_checkout_order($1, $2, $3, $4::jsonb, $5, $6)",
      args,
    );
    const retry = await database.query<{ order_id: string; total: string; created: boolean; order_created_at: Date }>(
      "select * from public.create_checkout_order($1, $2, $3, $4::jsonb, $5, $6)",
      args,
    );

    expect(first.rows[0].created).toBe(true);
    expect(first.rows[0].total).toBe("25.00");
    expect(retry.rows[0].created).toBe(false);
    expect(retry.rows[0].order_id).toBe(first.rows[0].order_id);
    expect(retry.rows[0].order_created_at).toEqual(first.rows[0].order_created_at);

    const counts = await database.query<{ orders: number; details: number }>(`
      select
        (select count(*)::integer from public.orders where checkout_request_key = '${requestKey}') as orders,
        (select count(*)::integer from public.order_details where order_id = '${first.rows[0].order_id}') as details
    `);
    expect(counts.rows[0]).toEqual({ orders: 1, details: 1 });
  });

  it("rejects replay with a different payload and products from another company", async () => {
    const args = [companyId, "Nuevo Cliente", "nuevo@example.com", JSON.stringify([{ productId, quantity: 1 }]), requestKey, "b".repeat(64)];
    await database.query("select * from public.create_checkout_order($1, $2, $3, $4::jsonb, $5, $6)", args);

    await expect(database.query(
      "select * from public.create_checkout_order($1, $2, $3, $4::jsonb, $5, $6)",
      [companyId, "Otro Nombre", "nuevo@example.com", JSON.stringify([{ productId, quantity: 1 }]), requestKey, "c".repeat(64)],
    )).rejects.toThrow();

    await expect(database.query(
      "select * from public.create_checkout_order($1, $2, $3, $4::jsonb, $5, $6)",
      [otherCompanyId, "Cliente", "otro@example.com", JSON.stringify([{ productId, quantity: 1 }]), "923e4567-e89b-42d3-a456-426614174000", "d".repeat(64)],
    )).rejects.toThrow();
  });

  it("enforces delivery transitions and anchors the 30-day window", async () => {
    const checkout = await database.query<{ order_id: string }>(
      "select order_id from public.create_checkout_order($1, $2, $3, $4::jsonb, $5, $6)",
      [companyId, "Cliente Entrega", "entrega@example.com", JSON.stringify([{ productId, quantity: 1 }]), requestKey, "e".repeat(64)],
    );
    const orderId = checkout.rows[0].order_id;
    const details = await database.query<{ id: string }>("select id from public.order_details where order_id = $1", [orderId]);
    const licenseKeys = JSON.stringify([{ detailId: details.rows[0].id, licenseKey: "LICENCIA-UNO" }]);

    await database.query("select public.update_order_with_details($1, $2, $3, $4::jsonb)", [companyId, orderId, "paid", "[]"]);
    await database.query("select public.update_order_with_details($1, $2, $3, $4::jsonb)", [companyId, orderId, "delivered", licenseKeys]);
    const firstDelivery = await database.query<{ delivered_at: Date }>("select delivered_at from public.orders where id = $1", [orderId]);
    const firstExpiry = await database.query<{ download_expires_at: Date; license_key: string }>("select download_expires_at, license_key from public.order_details where order_id = $1", [orderId]);

    await database.query("select public.update_order_with_details($1, $2, $3, $4::jsonb)", [companyId, orderId, "delivered", "[]"]);
    const retryExpiry = await database.query<{ download_expires_at: Date }>("select download_expires_at from public.order_details where order_id = $1", [orderId]);

    expect(new Date(firstExpiry.rows[0].download_expires_at).getTime() - new Date(firstDelivery.rows[0].delivered_at).getTime()).toBe(30 * 24 * 60 * 60 * 1000);
    expect(firstExpiry.rows[0].license_key).toBe("LICENCIA-UNO");
    expect(retryExpiry.rows[0].download_expires_at).toEqual(firstExpiry.rows[0].download_expires_at);
    await expect(database.query("select public.update_order_with_details($1, $2, $3, $4::jsonb)", [companyId, orderId, "pending", "[]"])).rejects.toThrow();
  });

  it("limits requests atomically and prevents removing the last active admin", async () => {
    const rateLimitKey = "f".repeat(64);
    expect((await database.query<{ allowed: boolean }>("select public.consume_rate_limit($1, 2, 60) as allowed", [rateLimitKey])).rows[0].allowed).toBe(true);
    expect((await database.query<{ allowed: boolean }>("select public.consume_rate_limit($1, 2, 60) as allowed", [rateLimitKey])).rows[0].allowed).toBe(true);
    expect((await database.query<{ allowed: boolean }>("select public.consume_rate_limit($1, 2, 60) as allowed", [rateLimitKey])).rows[0].allowed).toBe(false);

    await database.query("select public.register_staff_member($1, $2, $3, $4, $5)", [companyId, firstAdminId, "Admin Uno", "admin1@example.com", "admin"]);
    await expect(database.query("select public.update_staff_access($1, $2, $3, $4)", [companyId, firstAdminId, "support", false])).rejects.toThrow();

    await database.query("select public.register_staff_member($1, $2, $3, $4, $5)", [companyId, secondAdminId, "Admin Dos", "admin2@example.com", "admin"]);
    await database.query("select public.update_staff_access($1, $2, $3, $4)", [companyId, firstAdminId, "support", false]);
    const staff = await database.query<{ is_active: boolean }>("select is_active from public.users where id = $1", [firstAdminId]);
    expect(staff.rows[0].is_active).toBe(false);
  });
});
